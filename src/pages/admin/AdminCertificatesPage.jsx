import React, { useState, useEffect, useCallback } from 'react';
import { Link } from 'react-router-dom';
import { listAdminCertificates, approveCertificate, rejectCertificate, revokeCertificate, downloadAdminCertificatePdf } from '../../services/adminService.js';
import CertificatePreview from '../../components/certificates/CertificatePreview.jsx';
import {
  PageHeader, Toolbar, FilterPills, SearchInput, DataTable, Pagination,
  StatusBadge, Modal, ErrorBanner,
} from '../../components/ui/index.js';

// Generic confirm modal (reject / revoke — needs a reason field)
function ConfirmModal({ title, message, onConfirm, onCancel, confirmLabel, danger }) {
  const [reason, setReason] = useState('');
  return (
    <Modal open onClose={onCancel} title={title}
      footer={<>
        <button onClick={onCancel} className="btn-ghost text-sm">Cancel</button>
        <button onClick={() => onConfirm(reason)}
          className={`px-4 py-2 text-sm font-semibold text-white rounded-xl
            ${danger ? 'bg-red-600 hover:bg-red-700' : 'bg-primary-800 hover:bg-primary-700'}`}>
          {confirmLabel}
        </button>
      </>}>
      <p className="text-sm text-gray-600 mb-4">{message}</p>
      <textarea rows={3} placeholder="Reason (optional)" value={reason}
        onChange={e => setReason(e.target.value)}
        className="input resize-none" />
    </Modal>
  );
}

// Approve modal — cert number is auto-generated by backend; admin can optionally override it
function ApproveModal({ studentName, initialMarks, initialGrade, onConfirm, onCancel }) {
  const [marks,      setMarks]      = useState(initialMarks || '');
  const [grade,      setGrade]      = useState(initialGrade || '');
  const [certNumber, setCertNumber] = useState('');
  const [certError,  setCertError]  = useState('');

  const CERT_FORMAT = /^AICIT-\d{4}-\d{6}$/;

  const handleConfirm = () => {
    const trimmed = certNumber.trim().toUpperCase();
    if (trimmed && !CERT_FORMAT.test(trimmed)) {
      setCertError('Format must be AICIT-YYYY-XXXXXX  (e.g. AICIT-2026-000042)');
      return;
    }
    setCertError('');
    onConfirm({ marks: marks || null, grade: grade || null, customCertNumber: trimmed || null });
  };

  return (
    <Modal open onClose={onCancel} title="Approve Certificate"
      footer={<>
        <button onClick={onCancel} className="btn-ghost text-sm">Cancel</button>
        <button onClick={handleConfirm}
          className="px-4 py-2 text-sm font-semibold text-white bg-green-600 hover:bg-green-700 rounded-xl transition-colors">
          ✅ Approve &amp; Issue
        </button>
      </>}>
      <div className="space-y-4">
        <p className="text-sm text-gray-600">
          Approve and issue certificate for <span className="font-semibold">{studentName}</span>?
        </p>

        {/* Certificate Number */}
        <div>
          <label className="block text-xs font-semibold text-gray-500 uppercase mb-1">
            Certificate Number
            <span className="ml-1 text-gray-400 normal-case font-normal">(leave blank to auto-generate)</span>
          </label>
          <input
            type="text"
            value={certNumber}
            onChange={e => { setCertNumber(e.target.value); setCertError(''); }}
            placeholder="e.g. AICIT-2026-000042  or leave blank"
            className={`w-full px-3 py-2 text-sm border rounded-lg focus:outline-none focus:ring-2
              focus:ring-primary-500 font-mono tracking-wide
              ${certError ? 'border-red-400 bg-red-50' : 'border-gray-300'}`}
          />
          {certError && <p className="mt-1 text-xs text-red-600">{certError}</p>}
          {!certError && (
            <p className="mt-1 text-xs text-gray-400">Format: AICIT-YYYY-XXXXXX</p>
          )}
        </div>

        {/* Marks & Grade */}
        <div className="grid grid-cols-2 gap-4">
          <div>
            <label className="block text-xs font-semibold text-gray-500 uppercase mb-1">
              Marks <span className="text-gray-400 normal-case font-normal">(optional)</span>
            </label>
            <input type="text" value={marks} onChange={e => setMarks(e.target.value)}
              placeholder="e.g. 450/500"
              className="w-full px-3 py-2 text-sm border border-gray-300 rounded-lg
                         focus:outline-none focus:ring-2 focus:ring-primary-500" />
          </div>
          <div>
            <label className="block text-xs font-semibold text-gray-500 uppercase mb-1">
              Grade <span className="text-gray-400 normal-case font-normal">(optional)</span>
            </label>
            <input type="text" value={grade} onChange={e => setGrade(e.target.value)}
              placeholder="e.g. A+"
              className="w-full px-3 py-2 text-sm border border-gray-300 rounded-lg
                         focus:outline-none focus:ring-2 focus:ring-primary-500" />
          </div>
        </div>

        <p className="text-xs text-gray-400">
          A PDF certificate will be generated automatically upon approval.
        </p>
      </div>
    </Modal>
  );
}

const TABS = [
  { value: '',         label: 'All' },
  { value: 'REQUESTED', label: 'Pending Review' },
  { value: 'ISSUED',   label: 'Issued' },
  { value: 'REJECTED', label: 'Rejected' },
  { value: 'REVOKED',  label: 'Revoked' },
];

export default function AdminCertificatesPage() {
  const [certs,      setCerts]      = useState([]);
  const [pagination, setPagination] = useState({ totalElements: 0, totalPages: 0 });
  const [status,     setStatus]     = useState('REQUESTED');
  const [search,     setSearch]     = useState('');
  const [page,       setPage]       = useState(0);
  const [loading,    setLoading]    = useState(false);
  const [error,      setError]      = useState(null);
  const [modal,      setModal]      = useState(null); // { type: 'approve'|'reject'|'revoke', cert }
  const [preview,    setPreview]    = useState(null); // cert being previewed

  const load = useCallback(async () => {
    setLoading(true); setError(null);
    try {
      const res = await listAdminCertificates({ page, size: 20, status, search });
      setCerts(res.data?.content ?? []);
      setPagination({ totalElements: res.data?.totalElements ?? 0, totalPages: res.data?.totalPages ?? 0 });
    } catch (err) { setError(err.message); }
    finally { setLoading(false); }
  }, [page, status, search]);

  useEffect(() => { load(); }, [load]);

  const doAction = async (action, id, payload = {}) => {
    try {
      if (action === 'approve') await approveCertificate(id, { marks: payload.marks || null, grade: payload.grade || null, customCertNumber: payload.customCertNumber || null });
      if (action === 'reject')  await rejectCertificate(id, payload.reason || '');
      if (action === 'revoke')  await revokeCertificate(id, payload.reason || '');
      setModal(null);
      load();
    } catch (err) { setError(err.message); setModal(null); }
  };

  const handleDownload = async (id, certNumber) => {
    try {
      const blob = await downloadAdminCertificatePdf(id);
      if (!blob || blob.size === 0) { alert('PDF not available.'); return; }
      const url = URL.createObjectURL(blob);
      const a   = document.createElement('a');
      a.href = url; a.download = `${certNumber}.pdf`; a.click();
      URL.revokeObjectURL(url);
    } catch (err) { alert('Download failed: ' + err.message); }
  };

  const columns = [
    {
      key: 'certNumber', header: 'Cert Number', primary: true,
      render: (c) => (
        <div className="min-w-0">
          <span className="font-mono text-xs text-primary-800 font-semibold block truncate">{c.certificateNumber || '—'}</span>
          <span className="text-[11px] text-gray-400 truncate block max-w-[160px]">{c.studentName}</span>
        </div>
      ),
    },
    { key: 'course', header: 'Course', hideOnMobile: true,
      render: (c) => <span className="text-gray-600 block max-w-[150px] truncate">{c.courseName}</span> },
    { key: 'institute', header: 'Institute', hideOnMobile: true,
      render: (c) => <span className="text-gray-600 block max-w-[120px] truncate">{c.instituteName}</span> },
    { key: 'status', header: 'Status', render: (c) => <StatusBadge status={c.status} /> },
    {
      key: 'actions', header: 'Actions', align: 'right',
      render: (c) => (
        <div className="flex gap-2.5 flex-wrap justify-end items-center">
          {(c.status === 'REQUESTED' || c.status === 'UNDER_REVIEW') && (
            <>
              <button onClick={() => setModal({ type: 'approve', cert: c })}
                className="text-xs text-green-600 hover:underline font-semibold">Approve</button>
              <button onClick={() => setModal({ type: 'reject', cert: c })}
                className="text-xs text-red-600 hover:underline font-semibold">Reject</button>
            </>
          )}
          {c.status === 'ISSUED' && (
            <>
              <button onClick={() => setPreview(c)}
                className="text-xs text-primary-700 hover:underline font-semibold">👁 Preview</button>
              <button onClick={() => handleDownload(c.id, c.certificateNumber)}
                className="text-xs text-gray-500 hover:underline font-semibold">
                {c.certificateType === 'TYPING' ? '⬇ Typing Cert' : '⬇ AICIT Cert'}
              </button>
              <button onClick={() => setModal({ type: 'revoke', cert: c })}
                className="text-xs text-red-500 hover:underline font-semibold">Revoke</button>
            </>
          )}
          <Link to={`/admin/certificates/${c.id}`}
            className="text-xs text-gray-500 hover:underline font-medium">Detail</Link>
        </div>
      ),
    },
  ];

  return (
    <div className="space-y-5">
      {modal?.type === 'approve' && (
        <ApproveModal
          studentName={modal.cert.studentName}
          initialMarks={modal.cert.marks}
          initialGrade={modal.cert.grade}
          onCancel={() => setModal(null)}
          onConfirm={(payload) => doAction('approve', modal.cert.id, payload)}
        />
      )}
      {(modal?.type === 'reject' || modal?.type === 'revoke') && (
        <ConfirmModal
          title={modal.type === 'reject' ? 'Reject Certificate' : 'Revoke Certificate'}
          message={modal.type === 'reject'
            ? `Reject certificate request for ${modal.cert.studentName}?`
            : `Revoke certificate ${modal.cert.certificateNumber} for ${modal.cert.studentName}? It will show as REVOKED on public verification.`}
          onCancel={() => setModal(null)}
          onConfirm={(reason) => doAction(modal.type, modal.cert.id, { reason })}
          confirmLabel={modal.type === 'reject' ? 'Reject' : 'Revoke'}
          danger
        />
      )}

      <PageHeader title="Certificates" icon="📜"
        subtitle={`${pagination.totalElements} total certificate${pagination.totalElements === 1 ? '' : 's'}`} />

      <Toolbar>
        <div className="flex-1 min-w-0">
          <FilterPills options={TABS} value={status} onChange={(v) => { setStatus(v); setPage(0); }} />
        </div>
        <SearchInput className="sm:w-72" defaultValue={search}
          onSubmit={(v) => { setSearch(v); setPage(0); }}
          placeholder="Search by cert number or student…" />
      </Toolbar>

      <ErrorBanner message={error} onRetry={load} />

      <DataTable
        columns={columns}
        rows={certs}
        rowKey={(c) => c.id}
        loading={loading}
        empty={{ icon: '📜', title: 'No certificates found', message: 'Try adjusting the filters or search.' }}
      />

      <Pagination page={page} totalPages={pagination.totalPages}
        pageSize={20} totalElements={pagination.totalElements}
        onChange={setPage} />

      {preview && (
        <CertificatePreview
          cert={preview}
          scope="admin"
          onClose={() => setPreview(null)}
          serverPdf={{
            label: 'Official PDF',
            onDownload: () => handleDownload(preview.id, preview.certificateNumber),
          }}
        />
      )}
    </div>
  );
}
